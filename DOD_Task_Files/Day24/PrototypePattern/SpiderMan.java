public class SpiderMan extends HumanBeing {
    public SpiderMan() {
        type = "SpiderMan";
    }

    public void walk() {
        System.out.println("SpiderMan walks swiftly.");
    }

    public void see() {
        System.out.println("SpiderMan sees with spider-sense.");
    }

    public void talk() {
        System.out.println("SpiderMan talks with wit.");
    }

    public void crawling() {
        System.out.println("SpiderMan crawls on walls.");
    }

    public void throwingWeb() {
        System.out.println("SpiderMan throws web.");
    }
}