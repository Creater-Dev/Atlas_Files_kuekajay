public class IronMan extends HumanBeing {
    public IronMan() {
        type = "IronMan";
    }

    public void walk() {
        System.out.println("IronMan walks with a suit.");
    }

    public void see() {
        System.out.println("IronMan sees with HUD.");
    }

    public void talk() {
        System.out.println("IronMan talks with confidence.");
    }

    public void fly() {
        System.out.println("IronMan can fly.");
    }

    public void intelligent() {
        System.out.println("IronMan is a genius.");
    }

    public void fireShots() {
        System.out.println("IronMan fires shots.");
    }

    public void defendHimself() {
        System.out.println("IronMan defends himself.");
    }
}